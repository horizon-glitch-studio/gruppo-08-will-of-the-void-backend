package com.horizonglitch.wotv.battle;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import java.time.Instant;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;
import com.horizonglitch.wotv.deck.Deck;
import com.horizonglitch.wotv.player.Player;

/** A battle in any mode, or a challenge request waiting to be accepted.
 *
 * <p>The match itself is simulated by the {@code engine} module from the decks and the seed. */
@Entity
@Table(name = "battle")
@Getter
@Setter
@NoArgsConstructor
public class Battle {

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	private Long id;

	@Enumerated(EnumType.STRING)
	@Column(nullable = false, length = 8)
	private BattleMode mode;

	@Enumerated(EnumType.STRING)
	@Column(nullable = false, length = 10)
	private BattleStatus status;

	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "challenger_id", nullable = false)
	private Player challenger;

	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "opponent_id", nullable = false)
	private Player opponent;

	@ManyToOne(fetch = FetchType.LAZY)
	@JoinColumn(name = "challenger_deck_id")
	private Deck challengerDeck;

	/** Empty while the request is PENDING. */
	@ManyToOne(fetch = FetchType.LAZY)
	@JoinColumn(name = "opponent_deck_id")
	private Deck opponentDeck;

	/** Random seed generated by the server, so the battle can be replayed. */
	@Column
	private Long seed;

	@Enumerated(EnumType.STRING)
	@Column(length = 16)
	private BattleOutcome outcome;

	@Column(name = "challenger_energy")
	private Integer challengerEnergy;

	@Column(name = "opponent_energy")
	private Integer opponentEnergy;

	/** RANKED only. */
	@Column(name = "challenger_trophies_delta")
	private Integer challengerTrophiesDelta;

	/** RANKED only. */
	@Column(name = "opponent_trophies_delta")
	private Integer opponentTrophiesDelta;

	/** Copy of both decks as JSON; a pending request holds only the challenger's deck. */
	@JdbcTypeCode(SqlTypes.JSON)
	@Column(name = "decks_snapshot")
	private String decksSnapshot;

	@CreationTimestamp
	@Column(name = "created_at", nullable = false, updatable = false)
	private Instant createdAt;

	/** Deadline of a PENDING request (48 hours). */
	@Column(name = "expires_at")
	private Instant expiresAt;

	@Column(name = "played_at")
	private Instant playedAt;

	/** FRIEND and QUICK only. */
	@ManyToOne(fetch = FetchType.LAZY)
	@JoinColumn(name = "rematch_of_id")
	private Battle rematchOf;
}
